// Generate rpcd/lib/nuci/zoneinfo.uc: zone name -> POSIX TZ string, taken
// from the footer of each TZif file in the host tzdata. OpenWrt ships no
// zoneinfo, and uci system.timezone takes the POSIX string.
// Usage: node tools/gen-zoneinfo.mjs [/usr/share/zoneinfo]

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ZONEINFO = process.argv[2] ?? '/usr/share/zoneinfo';

function posixTz(zone) {
	const buf = readFileSync(join(ZONEINFO, zone));
	if (buf.toString('latin1', 0, 4) !== 'TZif') throw new Error(`${zone}: not TZif`);
	// v2+ files end with "\n<POSIX TZ>\n".
	const text = buf.toString('latin1');
	const end = text.lastIndexOf('\n');
	const start = text.lastIndexOf('\n', end - 1);
	const tz = text.slice(start + 1, end);
	if (!tz || /[^\x20-\x7e]/.test(tz)) throw new Error(`${zone}: no POSIX footer`);
	return tz;
}

const zones = new Set(['UTC']);
for (const line of readFileSync(join(ZONEINFO, 'zone.tab'), 'utf8').split('\n')) {
	if (!line || line.startsWith('#')) continue;
	const name = line.split('\t')[2];
	if (name) zones.add(name);
}

const entries = [...zones].sort().map((z) => [z, posixTz(z)]);
const version = (() => {
	try {
		return readFileSync(join(ZONEINFO, 'tzdata.zi'), 'utf8').match(/^# version (\S+)/m)?.[1];
	} catch {
		return undefined;
	}
})();

const body = entries.map(([z, tz]) => `\t'${z}': '${tz.replace(/'/g, "\\'")}',`).join('\n');
writeFileSync(
	join(ROOT, 'rpcd/lib/nuci/zoneinfo.uc'),
	`// SPDX-License-Identifier: Apache-2.0
//
// Generated by tools/gen-zoneinfo.mjs from tzdata${version ? ` ${version}` : ''}. Do not edit.
// Zone name -> POSIX TZ string (uci system.zonename -> system.timezone).

'use strict';

const zones = {
${body}
};

export { zones };
`,
);
console.log(`wrote ${entries.length} zones${version ? ` (tzdata ${version})` : ''}`);
